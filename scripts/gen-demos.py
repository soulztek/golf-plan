# Builds looping 2-frame animated WebP demos from yuhonas/free-exercise-db (Unlicense / public domain)
import json, os
from PIL import Image
FEDB = "/workspace/fedb"
d = json.load(open("scripts/demos.json")); meta = json.load(open("scripts/video_meta.json"))
ex = {e["id"]: e for e in json.load(open(f"{FEDB}/dist/exercises.json"))}
os.makedirs("public/img", exist_ok=True)
made = {}
for key, (fid, cues, note) in d["fedb"].items():
    if fid in made: continue
    frames = []
    for p in ex[fid]["images"][:2]:
        im = Image.open(f"{FEDB}/exercises/{p}").convert("RGB")
        w = 320; h = round(im.height * w / im.width)
        frames.append(im.resize((w, h), Image.LANCZOS))
    slug = fid.lower().replace("_", "-")
    out = f"public/img/{slug}.webp"
    frames[0].save(out, save_all=True, append_images=frames[1:], duration=900, loop=0, quality=62, method=6)
    made[fid] = {"file": f"img/{slug}.webp", "w": frames[0].width, "h": frames[0].height, "name": ex[fid]["name"]}
demos = {}
for key, (fid, cues, note) in d["fedb"].items():
    m = made[fid]
    demos[key] = {"img": m["file"], "w": m["w"], "h": m["h"], "src": m["name"], "cues": cues, "note": note or None}
for key, vids in d["videos"].items():
    demos.setdefault(key, {})["videos"] = [{"id": v, "title": meta[v]["title"], "channel": meta[v]["channel"]} for v in vids]
open("src/demos.generated.ts", "w").write("// generated by scripts/gen-demos.py\nexport const DEMOS: Record<string, any> = " + json.dumps(demos, indent=1, ensure_ascii=False) + ";\nexport const FEDB_USED: string[] = " + json.dumps(sorted(m["name"] for m in made.values())) + ";\n")
tot = sum(os.path.getsize("public/" + m["file"]) for m in made.values())
print(len(made), "images", round(tot / 1024), "KB;", len(demos), "demo keys")
